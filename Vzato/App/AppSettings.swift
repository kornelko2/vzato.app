import Foundation

/// UserDefaults keys and defaults shared by views (@AppStorage) and services.
/// Compiled into the app and the widget extension, so keep it free of UIKit/AppKit.
enum AppSettings {
    /// Shared container for the database and the few settings the widget needs. Set per platform
    /// in Config/Defaults.xcconfig (`VZATO_APP_GROUP`) and passed through Info.plist.
    static var appGroupIdentifier: String {
        (Bundle.main.object(forInfoDictionaryKey: "VzatoAppGroup") as? String).flatMap { $0.isEmpty ? nil : $0 }
            ?? "group.app.vzato"
    }

    static let appearanceKey = "appearance"
    static let snoozeMinutesKey = "snoozeMinutes"
    static let missedAfterMinutesKey = "missedAfterMinutes"
    static let lowStockNotificationsKey = "lowStockNotifications"
    static let repeatCountKey = "repeatCount"
    static let runOutWarningDaysKey = "runOutWarningDays"
    static let appIconKey = "appIcon"
    static let doseSoundKey = "doseSound"
    static let mealSoundKey = "mealSound"
    static let onboardingCompletedKey = "onboardingCompleted"

    static let defaultSnoozeMinutes = 10
    static let defaultMissedAfterMinutes = 120
    static let defaultRepeatCount = 2
    static let defaultRunOutWarningDays = 7

    static var isAppExtension: Bool { Bundle.main.bundleURL.pathExtension == "appex" }

    /// Settings live in the app's own defaults (that is where @AppStorage writes). The widget reads
    /// the copy the app places in the App Group defaults with `shareWithWidgets()`.
    static var defaults: UserDefaults {
        isAppExtension ? (UserDefaults(suiteName: appGroupIdentifier) ?? .standard) : .standard
    }

    static func shareWithWidgets() {
        let shared = UserDefaults(suiteName: appGroupIdentifier)
        shared?.set(missedAfterMinutes, forKey: missedAfterMinutesKey)
        // The widget schedules the "you can eat now" reminder after its Taken button.
        shared?.set(mealSound.rawValue, forKey: mealSoundKey)
        shared?.set(doseSound.rawValue, forKey: doseSoundKey)
    }

    static var snoozeMinutes: Int {
        let value = defaults.integer(forKey: snoozeMinutesKey)
        return value > 0 ? value : defaultSnoozeMinutes
    }

    static var missedAfterMinutes: Int {
        let value = defaults.integer(forKey: missedAfterMinutesKey)
        return value > 0 ? value : defaultMissedAfterMinutes
    }

    static var missedAfterInterval: TimeInterval { TimeInterval(missedAfterMinutes * 60) }

    /// Follow-up reminders after an unconfirmed dose (0 = off).
    static var repeatCount: Int {
        guard defaults.object(forKey: repeatCountKey) != nil else { return defaultRepeatCount }
        return max(0, min(3, defaults.integer(forKey: repeatCountKey)))
    }

    /// Days before the projected run-out date to warn (0 = off).
    static var runOutWarningDays: Int {
        guard defaults.object(forKey: runOutWarningDaysKey) != nil else { return defaultRunOutWarningDays }
        return max(0, min(30, defaults.integer(forKey: runOutWarningDaysKey)))
    }

    static var doseSound: ReminderSound {
        ReminderSound(rawValue: defaults.string(forKey: doseSoundKey) ?? "") ?? .chime
    }

    static var mealSound: ReminderSound {
        ReminderSound(rawValue: defaults.string(forKey: mealSoundKey) ?? "") ?? .soft
    }

    static var lowStockNotificationsEnabled: Bool {
        guard defaults.object(forKey: lowStockNotificationsKey) != nil else { return true }
        return defaults.bool(forKey: lowStockNotificationsKey)
    }
}

/// Notification sounds, generated by Scripts/make-sounds.py. Raw values are stored in settings,
/// so never rename an existing case.
enum ReminderSound: String, CaseIterable, Identifiable, Sendable {
    // Medication reminders: clear, attention-getting.
    case chime, twotone, glock, alert, droplets, dingdong
    // "You can eat now": gentle.
    case soft, marimba, harp, flute, gong, mealBell
    case system
    var id: String { rawValue }

    static let forDoses: [ReminderSound] = [.chime, .twotone, .glock, .alert, .droplets, .dingdong, .system]
    static let forMeals: [ReminderSound] = [.soft, .marimba, .harp, .flute, .gong, .mealBell, .system]

    var label: LocalizedStringResource {
        switch self {
        case .chime: "Chime"
        case .twotone: "Two-tone"
        case .glock: "Glockenspiel"
        case .alert: "Alert"
        case .droplets: "Droplets"
        case .dingdong: "Ding-dong"
        case .soft: "Soft melody"
        case .marimba: "Marimba"
        case .harp: "Harp"
        case .flute: "Flute"
        case .gong: "Gong"
        case .mealBell: "Meal bell"
        case .system: "System sound"
        }
    }

    /// File in the app bundle, nil for the system sound.
    var fileName: String? {
        switch self {
        case .chime: "vzato-dose.caf"
        case .twotone: "vzato-dose-twotone.caf"
        case .glock: "vzato-dose-glock.caf"
        case .alert: "vzato-dose-alert.caf"
        case .droplets: "vzato-dose-droplets.caf"
        case .dingdong: "vzato-dose-dingdong.caf"
        case .soft: "vzato-meal.caf"
        case .marimba: "vzato-meal-marimba.caf"
        case .harp: "vzato-meal-harp.caf"
        case .flute: "vzato-meal-flute.caf"
        case .gong: "vzato-meal-gong.caf"
        case .mealBell: "vzato-meal-bell.caf"
        case .system: nil
        }
    }
}

/// Debug-only launch arguments used for simulator screenshots and UI work.
enum LaunchArguments {
    /// `--onboarding` shows the first-start guide even if it was finished; `--no-onboarding` never
    /// shows it (UI tests that start from an empty store). `nil`: decide as usual.
    static var onboardingOverride: Bool? {
        #if DEBUG
        let args = CommandLine.arguments
        if args.contains("--onboarding") { return true }
        if args.contains("--no-onboarding") { return false }
        #endif
        return nil
    }

    static var initialTab: String? {
        #if DEBUG
        let args = CommandLine.arguments
        guard let index = args.firstIndex(of: "--tab"), index + 1 < args.count else { return nil }
        return args[index + 1]
        #else
        return nil
        #endif
    }

    /// `--open-medication <name>`: open that medication's detail (screenshots, UI checks).
    static var medicationToOpen: String? {
        #if DEBUG
        let args = CommandLine.arguments
        guard let index = args.firstIndex(of: "--open-medication"), index + 1 < args.count else { return nil }
        return args[index + 1]
        #else
        return nil
        #endif
    }

    /// `--edit`: together with `--open-medication`, go straight to the edit form.
    static var opensEditor: Bool {
        #if DEBUG
        return CommandLine.arguments.contains("--edit")
        #else
        return false
        #endif
    }

    /// `--reset-data`: start with an empty database (UI tests).
    static var resetsData: Bool {
        #if DEBUG
        return CommandLine.arguments.contains("--reset-data")
        #else
        return false
        #endif
    }

    static var opensFirstMedication: Bool {
        #if DEBUG
        return CommandLine.arguments.contains("--open-first-medication")
        #else
        return false
        #endif
    }
}
